export type CajaGeografica = { lonMin: number; lonMax: number; latMin: number; latMax: number };

const toca = (p: Poligono, m: CajaGeografica): boolean => {
  let lo0 = Infinity, lo1 = -Infinity, la0 = Infinity, la1 = -Infinity;
  for (const [lo, la] of p) { lo0 = Math.min(lo0, lo); lo1 = Math.max(lo1, lo); la0 = Math.min(la0, la); la1 = Math.max(la1, la); }
  return lo1 >= m.lonMin && lo0 <= m.lonMax && la1 >= m.latMin && la0 <= m.latMax;
};

/** Polígonos de tierra que caen (al menos en parte) dentro del marco, y el mar interior si lo toca. */
export function siluetaEuropa(m: CajaGeografica): { tierra: Poligono[]; mares: Poligono[] } {
  return { tierra: [CONTINENTE, ...ISLAS].filter((p) => toca(p, m)), mares: toca(MAR_NEGRO, m) ? [MAR_NEGRO] : [] };
}
